export function icon(graphics: typeof Graphics, name: keyof typeof patterns, size = 24) {
  const rows = patterns[name];
  if (!rows) throw new Error(`Unknown own icon: ${name}`);
  const source = graphics.imageFromAsciiArt(rows, { '.': 0, '#': 255 });
  const target = new graphics.GrayImage(size, size);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) target.pixels[y * size + x] = source.pixels[Math.floor(y * 12 / size) * 12 + Math.floor(x * 12 / size)];
  return target;
}

export function digit(graphics: typeof Graphics, character: string) {
  if (!/^[0-9]$/.test(character)) throw new Error(`Unknown digit: ${character}`);
  const cells = Array.from({ length: 23 }, () => Array(19).fill('.'));
  const row = (y: number, left: number, right: number) => cells[y].fill('#', left, right + 1);
  const block = (left: number, top: number, right: number, bottom: number) => {
    for (let y = top; y <= bottom; y++) row(y, left, right);
  };
  if (character === '1') {
    row(0, 8, 11);
    row(1, 7, 11);
    row(2, 6, 11);
    row(3, 5, 11);
    row(4, 4, 11);
    row(5, 4, 11);
    block(8, 6, 11, 19);
    row(20, 5, 14);
    row(21, 4, 14);
    row(22, 5, 13);
  } else {
    const active = segments[Number(character)];
    if (active.includes('a')) {
      row(0, 3, 15); row(1, 2, 16); row(2, 1, 17);
    }
    if (active.includes('b')) {
      row(2, 15, 17); block(16, 3, 18, 11);
      if (!active.includes('a')) { row(0, 16, 17); row(1, 16, 18); }
    }
    if (active.includes('c')) {
      block(16, 11, 18, 19); row(20, 15, 17);
      if (!active.includes('d')) { row(21, 16, 18); row(22, 16, 17); }
    }
    if (active.includes('d')) {
      row(20, 1, 17); row(21, 2, 16); row(22, 3, 15);
    }
    if (active.includes('e')) {
      block(0, 11, 2, 19); row(20, 1, 3);
    }
    if (active.includes('f')) {
      row(2, 1, 3); block(0, 3, 2, 11);
      if (!active.includes('a')) { row(0, 1, 2); row(1, 0, 2); }
    }
    if (active.includes('g')) {
      row(10, 1, 17); row(11, 0, 18); row(12, 1, 17);
    }
  }
  const source = graphics.imageFromAsciiArt(cells.map(line => line.join('')), { '.': 0, '#': 255 });
  const result = new graphics.GrayImage(56, 68);
  for (let y = 0; y < 23; y++) for (let x = 0; x < 19; x++) {
    if (source.pixels[y * 19 + x]) result.fillRect(x * 3, y * 3, 2, 2, 255);
  }
  return result;
}

export function dotText(image: GrayImage, x: number, y: number, text: string, value = 255) {
  for(const character of text) {
    const rows=small[character];
    if(!rows) throw new Error(`Unknown dot character: ${character}`);
    for(let j=0;j<rows.length;j++) for(let i=0;i<rows[j].length;i++) if(rows[j][i]==='#') image.fillRect(x+i*3,y+j*3,2,2,value);
    x += (rows[0].length+1)*3;
  }
}
